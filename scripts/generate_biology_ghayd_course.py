def build_biology_ghayd_course():
    parts = []
    order_idx = 1
    total_eus_count = 0

    for part_data in GHAYD_PARTS:
        eus = []
        eu_order = 1
        for item in part_data["items"]:
            eu = {
                "id": f"BI-QD-P{order_idx}-{eu_order}",
                "type": "correct_incorrect",
                "order": eu_order,
                "topic_tag": "قیدهای زیست‌شناسی",
                "payload": {
                    "statement": item["statement"],
                    "is_correct": item["is_correct"],
                    "explanation": item["explanation"]
                }
            }
            eus.append(eu)
            eu_order += 1
            total_eus_count += 1

        parts.append({
            "part_id": part_data["part_id"],
            "title": part_data["title"],
            "description": part_data["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "biology_ghayd",
        "title": "شکارگاه قیدهای زیست‌شناسی (دهم، یازدهم، دوازدهم)",
        "topic_code": "bi_ghayd",
        "subject": "زیست‌شناسی",
        "grade": "جامع کنکور",
        "description": "کالبدشکافی تمام گزاره‌های دام‌دار حاوی قیدهای «همه، هیچ، هر، اغلب، برخی، همیشه و به ندرت» برای نمره ۲۰ نهایی و درصد ۱۰۰ زیست کنکور",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/biology_ghayd.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {out_file}: {len(parts)} parts, {total_eus_count} total EUs.")

if __name__ == "__main__":
    build_biology_ghayd_course()
