def build_arabic_rules_course():
    parts = []
    order_idx = 1
    total_eus_count = 0

    for part_data in PARTS_DATA:
        eus = []
        eu_order = 1
        for item in part_data["items"]:
            eu_id = f"AR-RL-P{order_idx}-{eu_order}"
            eu_type = item["type"]

            if eu_type == "fill_in_the_blank":
                cleaned_kws = [k.strip() for k in item["keywords"] if k.strip() not in STOP_WORDS or len(k.strip()) > 3]
                p_load = {
                    "word": item["word"],
                    "translation": item["translation"],
                    "keywords": cleaned_kws,
                    "hint": item["hint"]
                }
            else:
                p_load = {
                    "statement": item["statement"],
                    "is_correct": item["is_correct"],
                    "explanation": item["explanation"]
                }

            eu = {
                "id": eu_id,
                "type": eu_type,
                "order": eu_order,
                "topic_tag": item["topic_tag"],
                "payload": p_load
            }
            eus.append(eu)
            eu_order += 1
            total_eus_count += 1

        parts.append({
            "part_id": part_data["part_id"],
            "title": part_data["title"],
            "description": part_data["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "arabic_translation_rules",
        "title": "فنون ترجمه و صیغه‌های افعال دام‌دار عربی",
        "topic_code": "ar_rules",
        "subject": "عربی",
        "grade": "جامع کنکور",
        "description": "فرمول‌های طلایی ترجمه ماضی استمراری، بعید، مضارع التزامی، ادوات نفی (لم، لن)، لای نفی جنس و اسلوب حصر",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/arabic_translation_rules.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {out_file}: {len(parts)} parts, {total_eus_count} total EUs.")

if __name__ == "__main__":
    build_arabic_rules_course()
