def build_dini12_course():
    parts = []
    order_idx = 1
    
    for lesson in LESSONS_DATA:
        eus = []
        part_order = 1
        for item in lesson["items"]:
            # Clean keywords to avoid any single stopwords
            cleaned_kws = []
            for kw in item["keywords"]:
                k = kw.strip()
                if k not in STOP_WORDS or len(k) > 4:
                    cleaned_kws.append(k)
            
            eu = {
                "id": f"D12-{lesson['lesson_id']}-{part_order}",
                "type": "fill_in_the_blank",
                "order": part_order,
                "topic_tag": "آیات و روایات نهایی",
                "payload": {
                    "word": item["word"],
                    "translation": item["translation"],
                    "keywords": cleaned_kws,
                    "hint": item["hint"],
                    "lesson_ref": item["lesson_ref"]
                }
            }
            eus.append(eu)
            part_order += 1
        
        parts.append({
            "part_id": f"dini12_p{lesson['lesson_id'][1:]}",
            "title": lesson["title"],
            "description": lesson["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "dini12_ayat",
        "title": "شاه‌کلید آیات و روایات دین و زندگی (۳) دوازدهم",
        "topic_code": "di12_ayat",
        "subject": "دین و زندگی",
        "grade": "پایه دوازدهم",
        "description": "پوشش ۱۰۰ درصدی بخش آیات، روایات و پیام‌های امتحانات نهایی خرداد و کنکور سراسری با کلیدواژه‌های رسمی مصححان سنجش",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/dini12_ayat.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    total_eus = sum(len(p["eus"]) for p in parts)
    print(f"Generated {out_file}: {len(parts)} lessons, {total_eus} total EUs.")

if __name__ == "__main__":
    build_dini12_course()
