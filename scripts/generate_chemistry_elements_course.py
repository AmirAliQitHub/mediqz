def build_chemistry_elements_course():
    parts = []
    order_idx = 1
    total_eus_count = 0

    for part_data in ELEMENTS_PARTS:
        eus = []
        eu_order = 1
        for item in part_data["items"]:
            eu_id = f"CH-PT-P{order_idx}-{eu_order}"
            
            # Format clean presentation
            word = f"عنصر شماره {item['z']}: {item['name']} ({item['symbol']})"
            translation = f"دوره {item['period']}، گروه {item['group']} | عدد اتمی: {item['z']} | آرایش: {item['config']}\nخواص و کاربردها: {item['features']}"
            
            cleaned_kws = [k.strip() for k in item["keywords"] if k.strip() not in STOP_WORDS or len(k.strip()) > 3]

            eu = {
                "id": eu_id,
                "type": "fill_in_the_blank",
                "order": eu_order,
                "topic_tag": "جدول تناوبی و عناصر",
                "payload": {
                    "word": word,
                    "translation": translation,
                    "keywords": cleaned_kws,
                    "hint": f"دوره {item['period']}، گروه {item['group']} - {item['features'][:60]}...",
                    "lesson_ref": f"شیمی پایه - دوره {item['period']}"
                }
            }
            eus.append(eu)
            eu_order += 1
            total_eus_count += 1

        parts.append({
            "part_id": part_data["part_id"],
            "title": part_data["title"],
            "description": part_data["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "chemistry_elements",
        "title": "جدول تناوبی هوشمند و ویژگی عناصر شیمی",
        "topic_code": "ch_pt",
        "subject": "شیمی",
        "grade": "جامع کنکور",
        "description": "تسلط کامل بر عناصر ۱ تا ۳۶، فلزات واسطه، آرایش‌های الکترونی، رنگ شعله و کاربردهای صنعتی کتاب‌های شیمی دهم، یازدهم و دوازدهم",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/chemistry_elements.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {out_file}: {len(parts)} parts, {total_eus_count} total EUs.")

if __name__ == "__main__":
    build_chemistry_elements_course()
