def build_chemistry_groups_course():
    parts = []
    order_idx = 1
    total_eus_count = 0

    for part_data in PARTS_DATA:
        eus = []
        eu_order = 1
        for item in part_data["items"]:
            eu_id = f"CH-FG-P{order_idx}-{eu_order}"
            eu_type = item["type"]

            if eu_type == "fill_in_the_blank":
                cleaned_kws = [k.strip() for k in item["keywords"] if k.strip() not in STOP_WORDS or len(k.strip()) > 2]
                p_load = {
                    "word": item["word"],
                    "translation": item["translation"],
                    "keywords": cleaned_kws,
                    "hint": item["hint"]
                }
            else:
                p_load = {
                    "statement": item["statement"],
                    "is_correct": item["is_correct"],
                    "explanation": item["explanation"]
                }

            eu = {
                "id": eu_id,
                "type": eu_type,
                "order": eu_order,
                "topic_tag": item["topic_tag"],
                "payload": p_load
            }
            eus.append(eu)
            eu_order += 1
            total_eus_count += 1

        parts.append({
            "part_id": part_data["part_id"],
            "title": part_data["title"],
            "description": part_data["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "chemistry_functional_groups",
        "title": "شناسنامه گروه‌های عاملی و شیمی آلی",
        "topic_code": "ch_groups",
        "subject": "شیمی",
        "grade": "جامع کنکور",
        "description": "تسلط کامل بر الکل، اتر، آلدهید، کتون، استر، آمین، آمید و داروهای شاخص کنکور (آسپرین، استامینوفن، کلوگزاسیلین، وانیلین)",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/chemistry_functional_groups.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {out_file}: {len(parts)} parts, {total_eus_count} total EUs.")

if __name__ == "__main__":
    build_chemistry_groups_course()
