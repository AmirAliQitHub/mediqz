def build_health12_course():
    parts = []
    order_idx = 1
    total_eus_count = 0

    for part_data in PARTS_DATA:
        eus = []
        eu_order = 1
        for item in part_data["eus"]:
            eu_id = f"HL12-P{order_idx}-{eu_order}"
            eu_type = item["type"]
            p_load = item["payload"]

            if eu_type == "fill_in_the_blank":
                cleaned_kws = [k.strip() for k in p_load["keywords"] if k.strip() not in STOP_WORDS or len(k.strip()) > 4]
                p_load["keywords"] = cleaned_kws

            eu = {
                "id": eu_id,
                "type": eu_type,
                "order": eu_order,
                "topic_tag": item["topic_tag"],
                "payload": p_load
            }
            eus.append(eu)
            eu_order += 1
            total_eus_count += 1

        parts.append({
            "part_id": part_data["part_id"],
            "title": part_data["title"],
            "description": part_data["description"],
            "order": order_idx,
            "eus": eus
        })
        order_idx += 1

    course_data = {
        "course_id": "health12",
        "title": "کپسول جامع حفظیات سلامت و بهداشت دوازدهم",
        "topic_code": "he12",
        "subject": "سلامت و بهداشت",
        "grade": "پایه دوازدهم",
        "description": "پوشش جامع و نهایی‌محور تعاریف، فرمول‌های BMI، هرم غذایی، بیماری‌های واگیر و غیرواگیر، ارگونومی و امداد با واحدهای تعاملی ۳ بعدی",
        "parts": parts
    }

    out_file = Path("backend/assets/courses/health12.json")
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(course_data, f, ensure_ascii=False, indent=2)

    print(f"Generated {out_file}: {len(parts)} parts, {total_eus_count} total EUs.")

if __name__ == "__main__":
    build_health12_course()
